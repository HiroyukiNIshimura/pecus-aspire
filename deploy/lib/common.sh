#!/bin/sh

if [ -z "${DEPLOY_DIR:-}" ]; then
  DEPLOY_DIR=$(CDPATH="" cd -- "$(dirname "$0")/.." && pwd -P)
fi
REPO_ROOT=$(CDPATH="" cd -- "$DEPLOY_DIR/.." && pwd -P)

# Used by scripts that source this file.
# shellcheck disable=SC2034
SERVICES="pecus-webapi pecus-frontend pecus-backfire pecus-dbmanager lexicalconverter"

die() {
  echo "[Error] $*" >&2
  exit 1
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "Required command not found: $1"
}

load_env() {
  env_file=${1:-"$DEPLOY_DIR/.env"}
  [ -f "$env_file" ] || die "Environment file not found: $env_file"
  # shellcheck disable=SC1090
  . "$env_file"
}

confirm_yes() {
  message=$1
  printf "[Confirm] %s. Type yes to continue [no]: " "$message" >&2
  read -r answer
  [ "$answer" = "yes" ] || {
    echo "[Abort] Cancelled." >&2
    exit 3
  }
}

ensure_env_file() {
  require_cmd node
  node "$REPO_ROOT/scripts/generate-appsettings.js" -P
  [ -f "$DEPLOY_DIR/.env" ] || die "Failed to generate $DEPLOY_DIR/.env"
}

compose() {
  [ -f "$DEPLOY_DIR/.env" ] ||
    die "deploy/.env is missing; deploy an immutable release first"
  COMPOSE_IGNORE_ORPHANS=1 docker compose \
    --env-file "$DEPLOY_DIR/.env" \
    --project-directory "$DEPLOY_DIR" \
    "$@"
}

compose_infra() {
  compose -f "$DEPLOY_DIR/docker-compose.infra.yml" "$@"
}

compose_app() {
  slot=$1
  shift
  compose -f "$DEPLOY_DIR/docker-compose.app-$slot.yml" "$@"
}

compose_monitoring() {
  compose -f "$DEPLOY_DIR/docker-compose.monitoring.yml" "$@"
}

compose_migrate() {
  compose \
    -f "$DEPLOY_DIR/docker-compose.infra.yml" \
    -f "$DEPLOY_DIR/docker-compose.migrate.yml" \
    "$@"
}

active_slot() {
  conf="$DEPLOY_DIR/nginx/conf.d/00-active-slot.conf"
  if [ ! -f "$conf" ]; then
    mkdir -p "$DEPLOY_DIR/nginx/conf.d"
    # The Nginx variable must remain literal.
    # shellcheck disable=SC2016
    printf '%s\n' '# Generated by deploy/ops/coati' 'geo $coati_active_slot {' '  default blue;' '}' >"$conf"
  fi
  slot=$(awk '/default[[:space:]]+(blue|green);/{print $2}' "$conf" | tr -d ';' | tail -n 1)
  case "$slot" in
    blue|green) printf '%s\n' "$slot" ;;
    *) die "Failed to detect active slot from $conf" ;;
  esac
}

set_active_slot() {
  slot=$1
  case "$slot" in blue|green) ;; *) die "Invalid slot: $slot" ;; esac
  conf="$DEPLOY_DIR/nginx/conf.d/00-active-slot.conf"
  mkdir -p "$DEPLOY_DIR/nginx/conf.d"
  # The Nginx variable must remain literal.
  # shellcheck disable=SC2016
  printf '%s\n' \
    '# Generated by deploy/ops/coati' \
    '# blue / green' \
    'geo $coati_active_slot {' \
    "  default $slot;" \
    '}' >"$conf"
  compose_infra exec -T nginx nginx -t
  compose_infra exec -T nginx nginx -s reload
}

wait_health() {
  container=$1
  timeout=${2:-300}
  start=$(date +%s)
  last_state=""
  while :; do
    running=$(docker inspect -f '{{.State.Running}}' "$container" 2>/dev/null || echo "")
    [ "$running" = "true" ] || {
      docker inspect "$container" --format '{{json .State}}' 2>/dev/null || true
      die "Container is not running: $container"
    }

    state=$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$container" 2>/dev/null || echo "")
    case "$state" in
      healthy) return 0 ;;
      starting|unhealthy|none)
        if [ "$state" != "$last_state" ]; then
          echo "[Wait] $container health: $state"
          last_state=$state
        fi
        ;;
      *) die "Unknown health state for $container: $state" ;;
    esac
    if [ $(( $(date +%s) - start )) -ge "$timeout" ]; then
      docker inspect "$container" --format '{{json .State.Health}}' 2>/dev/null || true
      docker logs --tail=80 "$container" >&2 2>&1 || true
      die "Health timeout: $container (last state: $state)"
    fi
    sleep 2
  done
}

wait_running() {
  container=$1
  timeout=${2:-120}
  start=$(date +%s)
  while :; do
    running=$(docker inspect -f '{{.State.Running}}' "$container" 2>/dev/null || echo "")
    [ "$running" = "true" ] && return 0
    [ $(( $(date +%s) - start )) -lt "$timeout" ] || die "Start timeout: $container"
    sleep 1
  done
}

image_label() {
  image=$1
  label=$2
  docker image inspect "$image" --format "{{ index .Config.Labels \"$label\" }}"
}

dockerfile_for_service() {
  case "$1" in
    pecus-webapi) echo "WebApi.Dockerfile" ;;
    pecus-frontend) echo "Frontend.Dockerfile" ;;
    pecus-backfire) echo "BackFire.Dockerfile" ;;
    pecus-dbmanager) echo "DbManager.Dockerfile" ;;
    lexicalconverter) echo "LexicalConverter.Dockerfile" ;;
    *) return 1 ;;
  esac
}

local_image_for_service() {
  service=$1
  slot=$2
  case "$service" in
    pecus-dbmanager) echo "coati-dbmanager:local" ;;
    lexicalconverter) echo "coati-lexicalconverter:local" ;;
    pecus-webapi) echo "coati-webapi-$slot:local" ;;
    pecus-frontend) echo "coati-frontend-$slot:local" ;;
    pecus-backfire) echo "coati-backfire-$slot:local" ;;
    *) return 1 ;;
  esac
}
